# To get sqrt from sqrt and pow function
import math

number = float(input("Enter a number to get its Square Root:- "))
sqr = math.sqrt(number)
root = math.pow(number , 0.5)
exp = number**0.5
print(f"Square Root of number using Sqrt function = {sqr}")
print(f"Square Root of number using Pow function = {root}")
print(f"Square Root of number using Exponential function = {exp}")

